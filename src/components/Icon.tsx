// Icons that point somewhere mirror in RTL.
const directional: ReadonlySet<IconName> = new Set<IconName>(['chevron', 'arrowBack', 'logout'])

export function Icon({ name, size = 22, strokeWidth = 1.75 }: { name: IconName; size?: number; strokeWidth?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={directional.has(name) ? 'flip-rtl' : undefined}
    >
      {paths[name]}
    </svg>
  )
}

export function isIconName(name: string): name is IconName {
  return Object.hasOwn(paths, name)
}
